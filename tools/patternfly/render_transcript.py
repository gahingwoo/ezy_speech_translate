#!/usr/bin/env python3
"""Generate app/templates/transcript.html: a service's transcript.

    python3 tools/patternfly/render_transcript.py

A page to read after the service, sent as a link to the people who were not
there: what was said, in the language the reader picks, in paragraphs rather
than captions, with what the speaker actually said under it when wanted. It is
also the printed copy: the browser's print, or its "Save as PDF", drops the
masthead and the controls and keeps the text.

The page is the app's shell without a sidebar, since there is nothing to
navigate to; the server fills it (app/user/transcripts.py).
"""
import pathlib
import sys

HERE = pathlib.Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))

from render_user import ROOT, LANG_NAMES, btn_icon, icon   # noqa: E402


def lang_options():
    """The listener page's languages, by their own name and the English one,
    as its language dialog lists them; the transcript's own is selected."""
    return "".join(
        '<option value="%s"{%% if lang == "%s" %%} selected{%% endif %%}>%s · %s</option>'
        % (code, code, native, english) if native != english else
        '<option value="%s"{%% if lang == "%s" %%} selected{%% endif %%}>%s</option>'
        % (code, code, native)
        for code, native, english in LANG_NAMES)


def build():
    return '''<!DOCTYPE html>
<!-- Generated by tools/patternfly/render_transcript.py. Edit that, not this. -->
<html lang="{{ lang or 'en' }}" data-version="{{ app_version }}">

<head>
  <meta charset="UTF-8">
  <meta content="width=device-width, initial-scale=1.0" name="viewport">
  <meta name="robots" content="noindex">
  <script>
    try {
      var t = localStorage.getItem('theme');
      if (t) {
        document.documentElement.setAttribute('data-theme', t);
        document.documentElement.classList.toggle('pf-v6-theme-dark', t === 'dark');
      }
    } catch (e) {}
  </script>
  <title>{%% if missing %%}EzySpeech{%% else %%}{{ room_name }} · {{ day }}{%% endif %%}</title>
  <link href="{{ static_url('patternfly/patternfly.css') }}" rel="stylesheet">
  <link href="{{ static_url('css/shell.css') }}" rel="stylesheet">
  <link href="{{ static_url('css/ezyspeech.css') }}" rel="stylesheet">
  <link href="{{ static_url('css/transcript.css') }}" rel="stylesheet">
  <script src="{{ static_url('js/oem-loader.js') }}"></script>
</head>

<body data-theme="light" data-page="transcript">
  <div class="pf-v6-c-page">
    <header class="pf-v6-c-masthead pf-m-display-inline" role="banner">
      <div class="pf-v6-c-masthead__main">
        <div class="pf-v6-c-masthead__brand">
          <!-- .brand and the order of its two spans are what oem-loader.js
               writes a customer's icon and name into. -->
          <div class="pf-v6-c-masthead__logo brand">
            <span aria-hidden="true"><img class="pf-v6-c-brand brand-mark" src="{{ static_url('img/mabc-mark.png') }}" width="208" height="208" alt=""></span>
            <span>EzySpeech</span>
          </div>
        </div>
      </div>
      <div class="pf-v6-c-masthead__content">
        <button class="pf-v6-c-button pf-m-plain masthead-action theme-toggle" type="button"
                id="themeToggle" aria-label="Dark Mode" title="Dark Mode"
                onclick="toggleTheme()">%(moon)s%(sun)s</button>
      </div>
    </header>

    <div class="pf-v6-c-page__main-container">
      <main class="pf-v6-c-page__main" tabindex="-1" id="main-content">
{%% if missing %%}
        <section class="pf-v6-c-page__main-section">
          <div class="pf-v6-c-empty-state">
            <div class="pf-v6-c-empty-state__content">
              <div class="pf-v6-c-empty-state__header">
                <div class="pf-v6-c-empty-state__icon">%(book)s</div>
                <div class="pf-v6-c-empty-state__title">
                  <h1 class="pf-v6-c-empty-state__title-text" data-i18n="tr_missingTitle">This transcript is not here</h1>
                </div>
              </div>
              <div class="pf-v6-c-empty-state__body" data-i18n="tr_missingText">The link may be cut short, or the service may have been deleted. Ask whoever sent it for the link again.</div>
            </div>
          </div>
        </section>
{%% else %%}
        <section class="pf-v6-c-page__main-section transcript-head">
          <div class="transcript-measure">
            <h1 class="pf-v6-c-title pf-m-2xl">{{ room_name }}</h1>
            <p class="transcript-when">
              <time id="transcriptDate" datetime="{{ date_iso }}">{{ day }}</time>
              <span class="transcript-hours">{{ first }}–{{ last }}</span>
            </p>
            <!-- The page's own controls, which print leaves out. -->
            <div class="pf-v6-c-toolbar transcript-tools">
              <div class="pf-v6-c-toolbar__content">
                <div class="pf-v6-c-toolbar__content-section">
                  <div class="pf-v6-c-toolbar__item">
                    <span class="pf-v6-c-form-control">
                      <select id="transcriptLang" aria-label="Language" data-i18n-aria-label="tr_language"
                              onchange="transcriptLanguage(this.value)">%(langs)s</select>
                      <span class="pf-v6-c-form-control__utilities">
                        <span class="pf-v6-c-form-control__toggle-icon">%(angle)s</span>
                      </span>
                    </span>
                  </div>
{%% if translated %%}
                  <div class="pf-v6-c-toolbar__item">
                    <label class="pf-v6-c-switch" for="transcriptSaid">
                      <input class="pf-v6-c-switch__input" type="checkbox" id="transcriptSaid"
                             onchange="transcriptShowSaid(this.checked)">
                      <span class="pf-v6-c-switch__toggle"></span>
                      <span class="pf-v6-c-switch__label" data-i18n="tr_showSaid">Show what was said</span>
                    </label>
                  </div>
{%% endif %%}
                  <div class="pf-v6-c-toolbar__item pf-m-align-end">
                    <button class="pf-v6-c-button pf-m-secondary" type="button" onclick="window.print()">
                      %(print)s<span class="pf-v6-c-button__text" data-i18n="tr_print">Print or save as PDF</span>
                    </button>
                  </div>
                  <div class="pf-v6-c-toolbar__item">
                    <a class="pf-v6-c-button pf-m-link" id="transcriptText"
                       href="/transcript/{{ room_id }}/{{ day }}.txt?k={{ key }}&amp;lang={{ lang }}">
                      %(download)s<span class="pf-v6-c-button__text" data-i18n="tr_download">Download text</span>
                    </a>
                  </div>
                </div>
              </div>
            </div>
          </div>
        </section>

        <section class="pf-v6-c-page__main-section transcript-body">
          <article class="transcript-measure transcript-text" id="transcriptText-body" lang="{{ lang }}">
{%% for p in paragraphs %%}
            <div class="transcript-paragraph">
              <span class="transcript-time">{{ p.at }}</span>
              <p class="transcript-read">{%% for r in p.read %%}{{ p.read_sep[loop.index0] }}{%% if r %%}{{ r }}{%% else %%}<span class="transcript-untranslated" title="Not translated" data-i18n-title="tr_notTranslated">{{ p.said[loop.index0] }}</span>{%% endif %%}{%% endfor %%}</p>
{%% if translated %%}
              <p class="transcript-said" lang="{{ spoken }}" hidden>{{ p.said_text }}</p>
{%% endif %%}
            </div>
{%% endfor %%}
          </article>
        </section>
{%% endif %%}
      </main>
    </div>
  </div>

  <script src="{{ static_url('js/i18n/core.js') }}"></script>
  <script src="{{ static_url('js/theme.js') }}"></script>
  <script src="{{ static_url('js/transcript.js') }}"></script>
</body>

</html>
''' % {"moon": icon("moon", "pf-v6-svg icon-moon"),
       "sun": icon("sun", "pf-v6-svg icon-sun"),
       "book": icon("book"), "angle": icon("angle-down"),
       "print": btn_icon("print"), "download": btn_icon("download"),
       "langs": lang_options()}


if __name__ == "__main__":
    out = ROOT / "app/templates/transcript.html"
    out.write_text(build(), encoding="utf-8")
    print("wrote %s (%d bytes)" % (out.relative_to(ROOT), out.stat().st_size))
