// Split the interface strings into one file per language.
//
//     node tools/i18n/build.mjs
//
// Evaluates app/i18n/strings.js as a browser would, so every merge and every
// fallback in it has already run, and writes what each language ends up with
// to app/static/js/i18n/<lang>.js. Then writes app/static/js/i18n/core.js:
// the list of those files, each with a hash of its contents so a changed
// language is never served from cache, followed by app/i18n/runtime.js.
//
// Fails, and writes nothing, if the split files would not rebuild exactly the
// tables the single file did.
//
